DROP TABLE IF EXISTS contacto_mensaje;
DROP TABLE IF EXISTS ruta_parada;
DROP TABLE IF EXISTS horario;
DROP TABLE IF EXISTS parada;
DROP TABLE IF EXISTS bus;
DROP TABLE IF EXISTS ruta_barrios_ordenados;
DROP TABLE IF EXISTS ruta_barrios;
DROP TABLE IF EXISTS agencia;
DROP TABLE IF EXISTS ruta;
DROP TABLE IF EXISTS conductor;
DROP TABLE IF EXISTS rol_usuario;
DROP TABLE IF EXISTS usuario;
DROP TABLE IF EXISTS rol;
DROP TABLE IF EXISTS barrio;

CREATE TABLE barrio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    localidad VARCHAR(255) NOT NULL,
    latitud DOUBLE,
    longitud DOUBLE
);

CREATE TABLE rol (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(20) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    provider VARCHAR(255),
    provider_id VARCHAR(255),
    password_setup_required BOOLEAN NOT NULL DEFAULT FALSE,
    role VARCHAR(255),
    nombres VARCHAR(255),
    apellidos VARCHAR(255),
    email VARCHAR(254) NOT NULL UNIQUE
);

CREATE TABLE rol_usuario (
    usuario_id BIGINT NOT NULL,
    rol_id BIGINT NOT NULL,
    PRIMARY KEY (usuario_id, rol_id)
);

CREATE TABLE conductor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_identificacion VARCHAR(30) NOT NULL UNIQUE,
    licencia_conducir VARCHAR(30),
    estado VARCHAR(20) NOT NULL,
    usuario_id BIGINT NOT NULL UNIQUE
);

CREATE TABLE ruta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    origen VARCHAR(150),
    destino VARCHAR(150),
    tiempo_estimado_min INTEGER,
    estado VARCHAR(20) NOT NULL,
    color_hex VARCHAR(7),
    descripcion CLOB,
    accesible_movilidad_reducida BOOLEAN NOT NULL,
    observaciones_accesibilidad CLOB,
    hora_aproximada TIME,
    verificada BOOLEAN
);

CREATE TABLE agencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    nit VARCHAR(255),
    direccion VARCHAR(255),
    telefono VARCHAR(255),
    email VARCHAR(255)
);

CREATE TABLE ruta_barrios (
    ruta_id BIGINT NOT NULL,
    barrios VARCHAR(255)
);

CREATE TABLE ruta_barrios_ordenados (
    ruta_id BIGINT NOT NULL,
    posicion INTEGER NOT NULL,
    barrio VARCHAR(255) NOT NULL,
    PRIMARY KEY (ruta_id, posicion)
);

CREATE TABLE bus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR(10) NOT NULL UNIQUE,
    modelo VARCHAR(50),
    color VARCHAR(30),
    conductor VARCHAR(100),
    numero_interno VARCHAR(20) NOT NULL UNIQUE,
    marca VARCHAR(50),
    capacidad_pasajeros INTEGER,
    anio INTEGER,
    estado VARCHAR(20) NOT NULL,
    accesible_movilidad_reducida BOOLEAN NOT NULL,
    nivel_ocupacion_actual VARCHAR(20),
    ultima_actualizacion_ocupacion TIMESTAMP,
    ruta_id BIGINT,
    agencia_id BIGINT
);

CREATE TABLE parada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100),
    direccion VARCHAR(300),
    ubicacion VARCHAR(255),
    referencia VARCHAR(255),
    barrio VARCHAR(100),
    estado VARCHAR(20) NOT NULL,
    accesible_movilidad_reducida BOOLEAN NOT NULL,
    tiene_sombra BOOLEAN,
    tiene_asientos BOOLEAN,
    observaciones_accesibilidad CLOB,
    orden INTEGER,
    latitud DOUBLE,
    longitud DOUBLE,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    ruta_id BIGINT
);

CREATE TABLE horario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sentido VARCHAR(10) NOT NULL,
    hora_salida TIME NOT NULL,
    hora_llegada TIME,
    frecuencia_min INTEGER,
    dias_semana VARCHAR(255),
    tipo_dia VARCHAR(10) NOT NULL,
    estado VARCHAR(10) NOT NULL,
    ruta_id BIGINT NOT NULL
);

CREATE TABLE ruta_parada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruta_id BIGINT,
    parada_id BIGINT,
    orden INTEGER
);

CREATE TABLE contacto_mensaje (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    apellido VARCHAR(255),
    telefono VARCHAR(255),
    email VARCHAR(255),
    mensaje VARCHAR(255)
);
