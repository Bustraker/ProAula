CREATE TABLE barrio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    localidad VARCHAR(255) NOT NULL,
    latitud DOUBLE,
    longitud DOUBLE
);

CREATE TABLE rol (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(20) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    provider VARCHAR(255),
    provider_id VARCHAR(255),
    password_setup_required BOOLEAN NOT NULL DEFAULT FALSE,
    role VARCHAR(255),
    nombres VARCHAR(255),
    apellidos VARCHAR(255),
    email VARCHAR(254) NOT NULL UNIQUE
);

CREATE TABLE rol_usuario (
    usuario_id BIGINT NOT NULL,
    rol_id BIGINT NOT NULL,
    PRIMARY KEY (usuario_id, rol_id)
);

CREATE TABLE conductor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_identificacion VARCHAR(30) NOT NULL UNIQUE,
    licencia_conducir VARCHAR(30),
    estado VARCHAR(20) NOT NULL,
    usuario_id BIGINT NOT NULL UNIQUE
);

CREATE TABLE ruta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    origen VARCHAR(150),
    destino VARCHAR(150),
    tiempo_estimado_min INTEGER,
    estado VARCHAR(20) NOT NULL,
    color_hex VARCHAR(7),
    descripcion CLOB,
    accesible_movilidad_reducida BOOLEAN NOT NULL,
    observaciones_accesibilidad CLOB,
    hora_aproximada TIME,
    verificada BOOLEAN
);

CREATE TABLE agencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    nit VARCHAR(255),
    direccion VARCHAR(255),
    telefono VARCHAR(255),
    email VARCHAR(255)
);

CREATE TABLE ruta_barrios (
    ruta_id BIGINT NOT NULL,
    barrios VARCHAR(255)
);

CREATE TABLE ruta_barrios_ordenados (
    ruta_id BIGINT NOT NULL,
    posicion INTEGER NOT NULL,
    barrio VARCHAR(255) NOT NULL,
    PRIMARY KEY (ruta_id, posicion)
);

CREATE TABLE bus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR(10) NOT NULL UNIQUE,
    modelo VARCHAR(50),
    color VARCHAR(30),
    conductor VARCHAR(100),
    numero_interno VARCHAR(20) NOT NULL UNIQUE,
    marca VARCHAR(50),
    capacidad_pasajeros INTEGER,
    anio INTEGER,
    estado VARCHAR(20) NOT NULL,
    accesible_movilidad_reducida BOOLEAN NOT NULL,
    nivel_ocupacion_actual VARCHAR(20),
    ultima_actualizacion_ocupacion TIMESTAMP,
    ruta_id BIGINT,
    agencia_id BIGINT
);

CREATE TABLE parada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100),
    direccion VARCHAR(300),
    ubicacion VARCHAR(255),
    referencia VARCHAR(255),
    barrio VARCHAR(100),
    estado VARCHAR(20) NOT NULL,
    accesible_movilidad_reducida BOOLEAN NOT NULL,
    tiene_sombra BOOLEAN,
    tiene_asientos BOOLEAN,
    observaciones_accesibilidad CLOB,
    orden INTEGER,
    latitud DOUBLE,
    longitud DOUBLE,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    ruta_id BIGINT
);

CREATE TABLE favorito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    tipo VARCHAR(10) NOT NULL,
    ruta_id BIGINT,
    parada_id BIGINT,
    fecha_creacion TIMESTAMP NOT NULL,
    CONSTRAINT uk_favorito_usuario_ruta UNIQUE (usuario_id, ruta_id),
    CONSTRAINT uk_favorito_usuario_parada UNIQUE (usuario_id, parada_id),
    CONSTRAINT chk_favorito_objetivo CHECK (
        (tipo = 'RUTA' AND ruta_id IS NOT NULL AND parada_id IS NULL)
        OR (tipo = 'PARADA' AND parada_id IS NOT NULL AND ruta_id IS NULL)
    ),
    CONSTRAINT fk_favorito_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE,
    CONSTRAINT fk_favorito_ruta FOREIGN KEY (ruta_id) REFERENCES ruta (id) ON DELETE CASCADE,
    CONSTRAINT fk_favorito_parada FOREIGN KEY (parada_id) REFERENCES parada (id) ON DELETE CASCADE
);

CREATE TABLE trayecto_favorito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    origen VARCHAR(255) NOT NULL,
    destino VARCHAR(255) NOT NULL,
    rutas_nombres VARCHAR(760) NOT NULL,
    barrios_recorridos VARCHAR(7800) NOT NULL,
    distancia_estimada_km DOUBLE,
    tiempo_estimado_auto_min INTEGER,
    paradas_count INTEGER NOT NULL,
    fecha_guardado TIMESTAMP NOT NULL,
    CONSTRAINT fk_trayecto_favorito_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE CASCADE
);

CREATE TABLE horario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sentido VARCHAR(10) NOT NULL,
    hora_salida TIME NOT NULL,
    hora_llegada TIME,
    frecuencia_min INTEGER,
    dias_semana VARCHAR(255),
    tipo_dia VARCHAR(10) NOT NULL,
    estado VARCHAR(10) NOT NULL,
    ruta_id BIGINT NOT NULL
);

CREATE TABLE ruta_parada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruta_id BIGINT,
    parada_id BIGINT,
    orden INTEGER
);

CREATE TABLE contacto_mensaje (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    apellido VARCHAR(255),
    telefono VARCHAR(255),
    email VARCHAR(255),
    mensaje VARCHAR(255)
);

CREATE TABLE admin_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(255) NOT NULL UNIQUE,
    descripcion VARCHAR(255),
    email VARCHAR(254),
    registration_request_id BIGINT UNIQUE
);

CREATE TABLE admin_code_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    nombres VARCHAR(100),
    apellidos VARCHAR(100),
    motivo VARCHAR(500),
    created_by VARCHAR(20),
    created_by_name VARCHAR(201),
    request_status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    decided_at TIMESTAMP,
    decided_by VARCHAR(20),
    code_email_sent_at TIMESTAMP,
    code_email_sent_by VARCHAR(20)
);

CREATE TABLE admin_invite_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_hash VARCHAR(64) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    used_at TIMESTAMP,
    version BIGINT
);

CREATE TABLE admin_push_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_email VARCHAR(254) NOT NULL,
    device_token CLOB NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL
);
